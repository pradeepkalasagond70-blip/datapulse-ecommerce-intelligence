"""
DataPulse - ML Feature Engineering

Purpose
-------
Build reusable, analysis-ready machine-learning features from the
validated e-commerce dataset.

This module sits between:
    Analytics -> Feature Engineering -> ML Models

Supported ML workflows
-----------------------
1. Customer churn prediction
2. Customer segmentation
3. Sales forecasting
4. Sales anomaly detection

Important
---------
- Does NOT perform EDA.
- Does NOT modify the original dataframe.
- Uses the schema mapping generated by schema_mapper.py.
- Handles missing optional fields gracefully.
- Produces stable feature tables for downstream ML modules.

Stable interface
----------------
build_ml_features(df, mapping) -> dict
"""

from __future__ import annotations

from typing import Any, Dict, Optional

import numpy as np
import pandas as pd


# ---------------------------------------------------------------------
# Constants
# ---------------------------------------------------------------------

CUSTOMER_FIELDS = [
    "customer_id",
    "customer_name",
]

PRODUCT_FIELDS = [
    "product_id",
    "product_name",
    "category",
    "subcategory",
    "brand",
]

SELLER_FIELDS = [
    "seller_id",
    "seller_name",
]

GEOGRAPHIC_FIELDS = [
    "region",
    "market",
]

FINANCIAL_FIELDS = [
    "sales_amount",
    "quantity",
    "unit_price",
    "cost",
    "profit",
]

DATE_FIELDS = [
    "order_date",
]

OPTIONAL_FIELDS = (
    CUSTOMER_FIELDS
    + PRODUCT_FIELDS
    + SELLER_FIELDS
    + GEOGRAPHIC_FIELDS
    + FINANCIAL_FIELDS
    + DATE_FIELDS
    + [
        "order_id",
        "order_status",
        "discount",
        "campaign_id",
        "channel",
        "payment_method",
        "device_type",
    ]
)


# ---------------------------------------------------------------------
# Generic helpers
# ---------------------------------------------------------------------

def _get_source_column(
    mapping: Dict[str, Any],
    canonical_field: str,
) -> Optional[str]:
    """
    Return the original dataframe column mapped to a canonical field.
    """

    if not mapping:
        return None

    mappings = mapping.get(
        "mappings",
        {},
    )

    value = mappings.get(
        canonical_field
    )

    if isinstance(value, dict):
        return (
            value.get("source_column")
            or value.get("column")
        )

    if isinstance(value, str):
        return value

    return None


def _safe_numeric(
    series: pd.Series,
) -> pd.Series:
    return pd.to_numeric(
        series,
        errors="coerce",
    )


def _safe_text(
    series: pd.Series,
    default: str = "Unknown",
) -> pd.Series:
    result = (
        series.astype("string")
        .str.strip()
    )

    result = result.replace(
        {
            "": pd.NA,
            "nan": pd.NA,
            "None": pd.NA,
            "null": pd.NA,
        }
    )

    return result.fillna(default)


def _safe_divide(
    numerator: pd.Series,
    denominator: pd.Series,
) -> pd.Series:
    numerator = pd.to_numeric(
        numerator,
        errors="coerce",
    ).fillna(0)

    denominator = pd.to_numeric(
        denominator,
        errors="coerce",
    )

    return (
        numerator
        .div(
            denominator.replace(
                0,
                np.nan,
            )
        )
        .replace(
            [np.inf, -np.inf],
            np.nan,
        )
        .fillna(0)
    )


def _empty_dataframe(
    columns: list[str],
) -> pd.DataFrame:
    return pd.DataFrame(
        columns=columns
    )


# ---------------------------------------------------------------------
# Standardized dataframe
# ---------------------------------------------------------------------

def _prepare_dataframe(
    df: pd.DataFrame,
    mapping: Dict[str, Any],
) -> pd.DataFrame:
    """
    Build a standardized internal dataframe using canonical names.
    """

    working = pd.DataFrame(
        index=df.index
    )

    for field in OPTIONAL_FIELDS:

        source_column = _get_source_column(
            mapping,
            field,
        )

        if (
            source_column
            and source_column in df.columns
        ):
            working[field] = df[
                source_column
            ]

    # Numeric fields
    for field in FINANCIAL_FIELDS:
        if field in working.columns:
            working[field] = _safe_numeric(
                working[field]
            )

    # Text fields
    text_fields = (
        CUSTOMER_FIELDS
        + PRODUCT_FIELDS
        + SELLER_FIELDS
        + GEOGRAPHIC_FIELDS
        + [
            "order_id",
            "order_status",
            "campaign_id",
            "channel",
            "payment_method",
            "device_type",
        ]
    )

    for field in text_fields:
        if field in working.columns:
            working[field] = _safe_text(
                working[field]
            )

    # Dates
    for field in DATE_FIELDS:
        if field in working.columns:
            working[field] = pd.to_datetime(
                working[field],
                errors="coerce",
            )

    return working


# ---------------------------------------------------------------------
# Financial feature preparation
# ---------------------------------------------------------------------

def _prepare_financial_features(
    working: pd.DataFrame,
) -> pd.DataFrame:
    """
    Add derived financial features.
    """

    result = working.copy()

    if (
        "profit" not in result.columns
        and "sales_amount" in result.columns
        and "cost" in result.columns
    ):
        result["profit"] = (
            result["sales_amount"]
            - result["cost"]
        )

    if (
        "unit_price" not in result.columns
        and "sales_amount" in result.columns
        and "quantity" in result.columns
    ):
        result["unit_price"] = _safe_divide(
            result["sales_amount"],
            result["quantity"],
        )

    if (
        "profit" in result.columns
        and "sales_amount" in result.columns
    ):
        result["profit_margin"] = _safe_divide(
            result["profit"] * 100,
            result["sales_amount"],
        )
    else:
        result["profit_margin"] = 0.0

    if (
        "discount" in result.columns
    ):
        discount = result["discount"]

        valid = discount.dropna()

        if (
            not valid.empty
            and valid.abs().quantile(
                0.95
            ) <= 1
        ):
            discount = discount * 100

        result["discount_pct"] = (
            discount
            .clip(lower=0)
            .fillna(0)
        )

    else:
        result["discount_pct"] = 0.0

    return result


# ---------------------------------------------------------------------
# Date features
# ---------------------------------------------------------------------

def _build_date_features(
    working: pd.DataFrame,
) -> pd.DataFrame:
    """
    Build calendar features useful for forecasting and anomaly
    detection.
    """

    result = working.copy()

    if "order_date" not in result.columns:
        return result

    date = result["order_date"]

    result["order_year"] = date.dt.year
    result["order_month"] = date.dt.month
    result["order_quarter"] = date.dt.quarter
    result["order_week"] = date.dt.isocalendar().week.astype(
        "Int64"
    )
    result["order_day"] = date.dt.day
    result["order_day_of_week"] = (
        date.dt.dayofweek
    )
    result["order_day_name"] = (
        date.dt.day_name()
    )
    result["order_weekend"] = (
        date.dt.dayofweek >= 5
    ).astype(int)

    result["year_month"] = (
        date.dt.to_period("M")
        .astype("string")
    )

    result["year_week"] = (
        date.dt.to_period("W")
        .astype("string")
    )

    return result


# ---------------------------------------------------------------------
# Customer-level features
# ---------------------------------------------------------------------

def _build_customer_features(
    working: pd.DataFrame,
) -> pd.DataFrame:
    """
    Build customer-level features.

    These features are designed to support:
    - churn
    - segmentation
    - customer value analysis
    """

    required = {
        "customer_id",
        "order_date",
    }

    if not required.issubset(
        working.columns
    ):
        return _empty_dataframe(
            [
                "customer_id",
                "revenue",
                "orders",
                "quantity",
                "profit",
                "average_order_value",
                "recency_days",
                "lifetime_days",
                "purchase_frequency",
                "avg_days_between_orders",
                "profit_margin",
                "discount_rate",
            ]
        )

    data = working.dropna(
        subset=[
            "customer_id",
            "order_date",
        ]
    ).copy()

    if data.empty:
        return _empty_dataframe(
            [
                "customer_id",
                "revenue",
                "orders",
                "quantity",
                "profit",
                "average_order_value",
                "recency_days",
                "lifetime_days",
                "purchase_frequency",
                "avg_days_between_orders",
                "profit_margin",
                "discount_rate",
            ]
        )

    reference_date = (
        data["order_date"]
        .max()
        + pd.Timedelta(days=1)
    )

    aggregations = {
        "revenue": (
            "sales_amount",
            "sum",
        ),
        "orders": (
            "order_id",
            "nunique",
        )
        if "order_id" in data.columns
        else (
            "sales_amount",
            "size",
        ),
        "quantity": (
            "quantity",
            "sum",
        )
        if "quantity" in data.columns
        else (
            "sales_amount",
            "size",
        ),
        "profit": (
            "profit",
            "sum",
        )
        if "profit" in data.columns
        else (
            "sales_amount",
            lambda x: 0.0,
        ),
        "first_purchase": (
            "order_date",
            "min",
        ),
        "last_purchase": (
            "order_date",
            "max",
        ),
        "average_discount_pct": (
            "discount_pct",
            "mean",
        ),
    }

    customer = (
        data.groupby(
            "customer_id",
            dropna=False,
        )
        .agg(**aggregations)
        .reset_index()
    )

    customer["average_order_value"] = (
        _safe_divide(
            customer["revenue"],
            customer["orders"],
        )
    )

    customer["recency_days"] = (
        reference_date
        - customer["last_purchase"]
    ).dt.days

    customer["lifetime_days"] = (
        customer["last_purchase"]
        - customer["first_purchase"]
    ).dt.days

    customer["lifetime_days"] = (
        customer["lifetime_days"]
        .clip(lower=0)
    )

    customer["purchase_frequency"] = (
        _safe_divide(
            customer["orders"],
            customer["lifetime_days"]
            + 1,
        )
    )

    # Calculate average gap between purchases.
    gap_values = []

    for customer_id, group in data.groupby(
        "customer_id"
    ):
        dates = (
            group["order_date"]
            .dropna()
            .sort_values()
            .drop_duplicates()
        )

        if len(dates) <= 1:
            gap = 0.0
        else:
            gap = float(
                dates.diff()
                .dt.days
                .dropna()
                .mean()
            )

        gap_values.append(
            {
                "customer_id": customer_id,
                "avg_days_between_orders": gap,
            }
        )

    gap_df = pd.DataFrame(
        gap_values
    )

    if not gap_df.empty:
        customer = customer.merge(
            gap_df,
            on="customer_id",
            how="left",
        )
    else:
        customer[
            "avg_days_between_orders"
        ] = 0.0

    customer["profit_margin"] = (
        _safe_divide(
            customer["profit"] * 100,
            customer["revenue"],
        )
    )

    customer["discount_rate"] = (
        customer["average_discount_pct"]
        .fillna(0)
    )

    # Repeat-customer flag
    customer["is_repeat_customer"] = (
        customer["orders"] >= 2
    ).astype(int)

    # RFM-style scoring
    customer["recency_score"] = (
        pd.qcut(
            customer["recency_days"]
            .rank(
                method="first"
            ),
            5,
            labels=False,
            duplicates="drop",
        )
    )

    # Reverse recency score so lower recency = better.
    if customer["recency_score"].notna().any():
        customer["recency_score"] = (
            customer["recency_score"]
            .max()
            - customer["recency_score"]
            + 1
        )

    customer["frequency_score"] = (
        pd.qcut(
            customer["orders"]
            .rank(
                method="first"
            ),
            5,
            labels=False,
            duplicates="drop",
        )
        + 1
    )

    customer["monetary_score"] = (
        pd.qcut(
            customer["revenue"]
            .rank(
                method="first"
            ),
            5,
            labels=False,
            duplicates="drop",
        )
        + 1
    )

    customer[
        "recency_score"
    ] = pd.to_numeric(
        customer["recency_score"],
        errors="coerce",
    ).fillna(1)

    customer[
        "frequency_score"
    ] = pd.to_numeric(
        customer["frequency_score"],
        errors="coerce",
    ).fillna(1)

    customer[
        "monetary_score"
    ] = pd.to_numeric(
        customer["monetary_score"],
        errors="coerce",
    ).fillna(1)

    customer["rfm_score"] = (
        customer["recency_score"]
        + customer["frequency_score"]
        + customer["monetary_score"]
    )

    customer["ltv_proxy"] = (
        customer["average_order_value"]
        * customer["purchase_frequency"]
        * 365
    )

    customer["annualized_revenue_proxy"] = (
        customer["revenue"]
        / (
            customer["lifetime_days"]
            .clip(lower=1)
            / 365
        )
    )

    return customer.sort_values(
        "revenue",
        ascending=False,
    ).reset_index(
        drop=True
    )


# ---------------------------------------------------------------------
# Product-level features
