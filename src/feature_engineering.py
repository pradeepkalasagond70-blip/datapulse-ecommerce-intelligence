def _build_product_features(
    working: pd.DataFrame,
) -> pd.DataFrame:
    """Build product-level ML features."""

    product_field = None

    if "product_id" in working.columns:
        product_field = "product_id"

    elif "product_name" in working.columns:
        product_field = "product_name"

    if product_field is None:
        return _empty_dataframe(
            [
                "product",
                "revenue",
                "quantity",
                "orders",
                "profit",
                "average_unit_price",
                "average_discount_pct",
                "profit_margin",
            ]
        )

    result = (
        working.groupby(
            product_field,
            dropna=False,
        )
        .agg(
            revenue=(
                "sales_amount",
                "sum",
            ),
            quantity=(
                "quantity",
                "sum",
            )
            if "quantity" in working.columns
            else (
                "sales_amount",
                "size",
            ),
            orders=(
                "order_id",
                "nunique",
            )
            if "order_id" in working.columns
            else (
                "sales_amount",
                "size",
            ),
            profit=(
                "profit",
                "sum",
            )
            if "profit" in working.columns
            else (
                "sales_amount",
                lambda x: 0.0,
            ),
            average_unit_price=(
                "unit_price",
                "mean",
            )
            if "unit_price" in working.columns
            else (
                "sales_amount",
                "mean",
            ),
            average_discount_pct=(
                "discount_pct",
                "mean",
            ),
        )
        .reset_index()
        .rename(
            columns={
                product_field: "product"
            }
        )
    )

    result["profit_margin"] = (
        _safe_divide(
            result["profit"] * 100,
            result["revenue"],
        )
    )

    return result.sort_values(
        "revenue",
        ascending=False,
    ).reset_index(
        drop=True
    )


# ---------------------------------------------------------------------
# Sales time-series features
# ---------------------------------------------------------------------

def _build_sales_time_series(
    working: pd.DataFrame,
) -> pd.DataFrame:
    """
    Build monthly sales time series.

    Includes lag and rolling features required by forecasting and
    anomaly detection.
    """

    required = {
        "order_date",
        "sales_amount",
    }

    if not required.issubset(
        working.columns
    ):
        return _empty_dataframe(
            [
                "period",
                "revenue",
                "orders",
                "quantity",
                "profit",
            ]
        )

    data = working.dropna(
        subset=[
            "order_date"
        ]
    ).copy()

    if data.empty:
        return _empty_dataframe(
            [
                "period",
                "revenue",
                "orders",
                "quantity",
                "profit",
            ]
        )

    data["period"] = (
        data["order_date"]
        .dt.to_period("M")
        .dt.to_timestamp()
    )

    result = (
        data.groupby(
            "period"
        )
        .agg(
            revenue=(
                "sales_amount",
                "sum",
            ),
            orders=(
                "order_id",
                "nunique",
            )
            if "order_id" in data.columns
            else (
                "sales_amount",
                "size",
            ),
            quantity=(
                "quantity",
                "sum",
            )
            if "quantity" in data.columns
            else (
                "sales_amount",
                "size",
            ),
            profit=(
                "profit",
                "sum",
            )
            if "profit" in data.columns
            else (
                "sales_amount",
                lambda x: 0.0,
            ),
        )
        .reset_index()
        .sort_values(
            "period"
        )
        .reset_index(
            drop=True
        )
    )

    # Growth
    result["revenue_change"] = (
        result["revenue"].diff()
    )

    result["revenue_growth_pct"] = (
        result["revenue"]
        .pct_change()
        .replace(
            [np.inf, -np.inf],
            np.nan,
        )
        * 100
    )

    # Lags
    result["revenue_lag_1"] = (
        result["revenue"].shift(1)
    )

    result["revenue_lag_2"] = (
        result["revenue"].shift(2)
    )

    result["revenue_lag_3"] = (
        result["revenue"].shift(3)
    )

    # Rolling averages
    result["revenue_rolling_3"] = (
        result["revenue"]
        .rolling(
            window=3,
            min_periods=1,
        )
        .mean()
    )

    result["revenue_rolling_6"] = (
        result["revenue"]
        .rolling(
            window=6,
            min_periods=1,
        )
        .mean()
    )

    # Rolling volatility
    result["revenue_rolling_std_3"] = (
        result["revenue"]
        .rolling(
            window=3,
            min_periods=2,
        )
        .std()
        .fillna(0)
    )

    # Time index
    result["time_index"] = np.arange(
        len(result)
    )

    result["month_number"] = (
        result["period"].dt.month
    )

    result["quarter"] = (
        result["period"].dt.quarter
    )

    return result


# ---------------------------------------------------------------------
# Transaction-level anomaly features
# ---------------------------------------------------------------------

def _build_anomaly_features(
    working: pd.DataFrame,
) -> pd.DataFrame:
    """
    Build transaction-level anomaly features.

    These features can be consumed by Isolation Forest or other
    anomaly detection models.
    """

    if "sales_amount" not in working.columns:
        return _empty_dataframe(
            [
                "sales_amount",
                "quantity",
                "unit_price",
                "profit",
                "discount_pct",
            ]
        )

    data = working.copy()

    features = pd.DataFrame(
        index=data.index
    )

    features["sales_amount"] = (
        data["sales_amount"]
        .fillna(
            data["sales_amount"].median()
        )
    )

    if "quantity" in data.columns:
        features["quantity"] = (
            data["quantity"]
            .fillna(
                data["quantity"].median()
            )
        )
    else:
        features["quantity"] = 0.0

    if "unit_price" in data.columns:
        features["unit_price"] = (
            data["unit_price"]
            .fillna(
                data["unit_price"].median()
            )
        )
    else:
        features["unit_price"] = (
            _safe_divide(
                features["sales_amount"],
                features["quantity"],
            )
        )

    if "profit" in data.columns:
        features["profit"] = (
            data["profit"]
            .fillna(0)
        )
    else:
        features["profit"] = 0.0

    if "discount_pct" in data.columns:
        features["discount_pct"] = (
            data["discount_pct"]
            .fillna(0)
        )
    else:
        features["discount_pct"] = 0.0

    if "order_date" in data.columns:
        features["day_of_week"] = (
            data["order_date"]
            .dt.dayofweek
            .fillna(0)
        )

        features["month"] = (
            data["order_date"]
            .dt.month
            .fillna(0)
        )
    else:
        features["day_of_week"] = 0
        features["month"] = 0

    # Log transformation helps models handle highly skewed sales.
    features["log_sales_amount"] = np.log1p(
        features["sales_amount"].clip(
            lower=0
        )
    )

    features["log_quantity"] = np.log1p(
        features["quantity"].clip(
            lower=0
        )
    )

    # Margin
    features["profit_margin"] = (
        _safe_divide(
            features["profit"] * 100,
            features["sales_amount"],
        )
    )

    return features.reset_index(
        drop=True
    )


# ---------------------------------------------------------------------
# Feature metadata
# ---------------------------------------------------------------------

def _build_feature_metadata(
    customer_features: pd.DataFrame,
    product_features: pd.DataFrame,
    sales_time_series: pd.DataFrame,
    anomaly_features: pd.DataFrame,
) -> Dict[str, Any]:
    """Describe generated ML feature sets."""

    return {
        "customer_features": {
            "available": not customer_features.empty,
            "rows": int(
                len(customer_features)
            ),
            "features": list(
                customer_features.columns
            ),
        },
        "product_features": {
            "available": not product_features.empty,
            "rows": int(
                len(product_features)
            ),
            "features": list(
                product_features.columns
            ),
        },
        "sales_time_series": {
            "available": not sales_time_series.empty,
            "rows": int(
                len(sales_time_series)
            ),
            "features": list(
                sales_time_series.columns
            ),
        },
        "anomaly_features": {
            "available": not anomaly_features.empty,
            "rows": int(
                len(anomaly_features)
            ),
            "features": list(
                anomaly_features.columns
            ),
        },
    }


# ---------------------------------------------------------------------
# Capability detection
# ---------------------------------------------------------------------

def _build_capabilities(
    working: pd.DataFrame,
    customer_features: pd.DataFrame,
    product_features: pd.DataFrame,
    sales_time_series: pd.DataFrame,
    anomaly_features: pd.DataFrame,
) -> Dict[str, bool]:
    """Determine which ML pipelines have usable feature sets."""

    return {
        "churn_features": (
            not customer_features.empty
            and "customer_id"
            in customer_features.columns
            and "recency_days"
            in customer_features.columns
        ),
        "segmentation_features": (
            not customer_features.empty
            and "customer_id"
            in customer_features.columns
            and len(customer_features) >= 3
        ),
        "forecasting_features": (
            not sales_time_series.empty
            and len(sales_time_series) >= 3
        ),
        "anomaly_features": (
            not anomaly_features.empty
            and len(anomaly_features) >= 5
        ),
        "product_features": (
            not product_features.empty
        ),
    }


# ---------------------------------------------------------------------
# Main public function
# ---------------------------------------------------------------------

def build_ml_features(
    df: pd.DataFrame,
    mapping: Dict[str, Any],
) -> Dict[str, Any]:
    """
    Build all reusable ML feature sets.

    Returns
    -------
    dict
        Stable feature-engineering contract:

        {
            "available": bool,
            "customer_features": DataFrame,
            "product_features": DataFrame,
            "sales_time_series": DataFrame,
            "anomaly_features": DataFrame,
            "metadata": dict,
            "capabilities": dict,
            "warnings": list,
        }
    """

    if (
        df is None
        or not isinstance(df, pd.DataFrame)
        or df.empty
    ):
        return {
            "available": False,
            "customer_features": pd.DataFrame(),
            "product_features": pd.DataFrame(),
            "sales_time_series": pd.DataFrame(),
            "anomaly_features": pd.DataFrame(),
            "metadata": {},
            "capabilities": {},
            "warnings": [
                "A non-empty pandas DataFrame is required."
            ],
        }

    # Standardize according to schema mapping.
    working = _prepare_dataframe(
        df,
        mapping,
    )

    # Derived financial features.
    working = _prepare_financial_features(
        working
    )

    # Calendar features.
    working = _build_date_features(
        working
    )

    # Customer ML features.
    customer_features = (
        _build_customer_features(
            working
        )
    )

    # Product features.
    product_features = (
        _build_product_features(
            working
        )
    )

    # Forecasting time series.
    sales_time_series = (
        _build_sales_time_series(
            working
        )
    )

    # Transaction anomaly features.
    anomaly_features = (
        _build_anomaly_features(
            working
        )
    )

    capabilities = _build_capabilities(
        working,
        customer_features,
        product_features,
        sales_time_series,
        anomaly_features,
    )

    metadata = _build_feature_metadata(
        customer_features,
        product_features,
        sales_time_series,
        anomaly_features,
    )

    warnings = []

    if not capabilities["churn_features"]:
        warnings.append(
            "Customer churn features are unavailable or insufficient."
        )

    if not capabilities["segmentation_features"]:
        warnings.append(
            "Customer segmentation features are unavailable "
            "or fewer than 3 customers are available."
        )

    if not capabilities["forecasting_features"]:
        warnings.append(
            "Sales forecasting requires at least 3 monthly periods."
        )

    if not capabilities["anomaly_features"]:
        warnings.append(
            "Anomaly detection requires at least 5 usable records."
        )

    return {
        "available": True,
        "customer_features": customer_features,
        "product_features": product_features,
        "sales_time_series": sales_time_series,
        "anomaly_features": anomaly_features,
        "metadata": metadata,
        "capabilities": capabilities,
        "warnings": warnings,
    }


